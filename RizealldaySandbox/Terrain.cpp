namespace {
	constexpr int kMinResolution = 2;
	constexpr int kMaxResolution = 513; // 512 x 512 quads: half a million triangles

	float LatticeValue(int x, int z, int seed)
	{
		uint32_t h = static_cast<uint32_t>(x) * 374761393u + static_cast<uint32_t>(z) * 668265263u + static_cast<uint32_t>(seed) * 2147483647u;
		h = (h ^ (h >> 13)) * 1274126177u;
		h ^= h >> 16;
		return static_cast<float>(h & 0xFFFFFFu) / 16777215.0f;
	}

	float ValueNoise(float x, float z, int seed)
	{
		const float floorX = std::floor(x);
		const float floorZ = std::floor(z);
		const int cellX = static_cast<int>(floorX);
		const int cellZ = static_cast<int>(floorZ);
		const auto smooth = [](float t) { return t * t * (3.0f - 2.0f * t); };
		const float tx = smooth(x - floorX);
		const float tz = smooth(z - floorZ);
		const float near0 = LatticeValue(cellX, cellZ, seed) + (LatticeValue(cellX + 1, cellZ, seed) - LatticeValue(cellX, cellZ, seed)) * tx;
		const float far0 = LatticeValue(cellX, cellZ + 1, seed) + (LatticeValue(cellX + 1, cellZ + 1, seed) - LatticeValue(cellX, cellZ + 1, seed)) * tx;
		return near0 + (far0 - near0) * tz;
	}
}

TerrainHeights GenerateTerrainNoise(int resolution, int seed, float frequency, int octaves)
{
	TerrainHeights result;
	result.resolution = std::clamp(resolution, kMinResolution, kMaxResolution);
	result.values.resize(static_cast<size_t>(result.resolution) * result.resolution);
	const float baseFrequency = std::isfinite(frequency) ? std::clamp(frequency, 0.01f, 1000.0f) : 1.0f;
	const int layers = std::clamp(octaves, 1, 8);
	const float last = static_cast<float>(result.resolution - 1);
	for (int z = 0; z < result.resolution; ++z) {
		for (int x = 0; x < result.resolution; ++x) {
			float value = 0.0f;
			float amplitude = 1.0f;
			float total = 0.0f;
			float layerFrequency = baseFrequency;
			for (int layer = 0; layer < layers; ++layer) {
				value += ValueNoise(x / last * layerFrequency, z / last * layerFrequency, seed + layer * 101) * amplitude;
				total += amplitude;
				amplitude *= 0.5f;
				layerFrequency *= 2.0f;
			}
			result.values[static_cast<size_t>(z) * result.resolution + x] = value / total;
		}
	}
	return result;
}

TerrainHeights TerrainFromImage(const std::vector<uint8_t>& pixels, int width, int height, int resolution)
{
	TerrainHeights result;
	result.resolution = std::clamp(resolution, kMinResolution, kMaxResolution);
	result.values.assign(static_cast<size_t>(result.resolution) * result.resolution, 0.0f);
	if (width <= 0 || height <= 0 || pixels.size() < static_cast<size_t>(width) * height) return result;
	const float last = static_cast<float>(result.resolution - 1);
	const auto pixel = [&](int x, int y) { return pixels[static_cast<size_t>(y) * width + x] / 255.0f; };
	for (int z = 0; z < result.resolution; ++z) {
		for (int x = 0; x < result.resolution; ++x) {
			const float u = x / last * (width - 1);
			const float v = (1.0f - z / last) * (height - 1); // image row 0 is the far edge
			const int x0 = static_cast<int>(u);
			const int y0 = static_cast<int>(v);
			const int x1 = (std::min)(x0 + 1, width - 1);
			const int y1 = (std::min)(y0 + 1, height - 1);
			const float tx = u - x0;
			const float ty = v - y0;
			const float top = pixel(x0, y0) + (pixel(x1, y0) - pixel(x0, y0)) * tx;
			const float bottom = pixel(x0, y1) + (pixel(x1, y1) - pixel(x0, y1)) * tx;
			result.values[static_cast<size_t>(z) * result.resolution + x] = top + (bottom - top) * ty;
		}
	}
	return result;
}

std::string BuildTerrainObj(const TerrainHeights& heights, float size, float height, float uvRepeat)
{
	const int n = heights.resolution;
	if (n < 2 || heights.values.size() < static_cast<size_t>(n) * n) return {};
	const float step = size / static_cast<float>(n - 1);
	std::string obj;
	obj.reserve(static_cast<size_t>(n) * n * 90);
	obj += "# Generated by the Terrain component\n";
	for (int z = 0; z < n; ++z) {
		for (int x = 0; x < n; ++x) {
			obj += std::format("v {:.4f} {:.4f} {:.4f}\n", -size * 0.5f + x * step, heights.At(x, z) * height, -size * 0.5f + z * step);
		}
	}
	for (int z = 0; z < n; ++z) {
		for (int x = 0; x < n; ++x) {
			obj += std::format("vt {:.4f} {:.4f}\n", uvRepeat * x / (n - 1), uvRepeat * z / (n - 1));
		}
	}
	for (int z = 0; z < n; ++z) {
		for (int x = 0; x < n; ++x) {
			const float dx = (heights.At((std::min)(x + 1, n - 1), z) - heights.At((std::max)(x - 1, 0), z)) * height;
			const float dz = (heights.At(x, (std::min)(z + 1, n - 1)) - heights.At(x, (std::max)(z - 1, 0))) * height;
			const float spanX = step * static_cast<float>((std::min)(x + 1, n - 1) - (std::max)(x - 1, 0));
			const float spanZ = step * static_cast<float>((std::min)(z + 1, n - 1) - (std::max)(z - 1, 0));
			const float nx = -dx / spanX;
			const float nz = -dz / spanZ;
			const float length = std::sqrt(nx * nx + 1.0f + nz * nz);
			obj += std::format("vn {:.4f} {:.4f} {:.4f}\n", nx / length, 1.0f / length, nz / length);
		}
	}
	const auto face = [&](int a, int b, int c) { obj += std::format("f {0}/{0}/{0} {1}/{1}/{1} {2}/{2}/{2}\n", a, b, c); };
	for (int z = 0; z + 1 < n; ++z) {
		for (int x = 0; x + 1 < n; ++x) {
			const int here = z * n + x + 1; // OBJ counts from 1
			face(here, here + n, here + 1);
			face(here + 1, here + n, here + n + 1);
		}
	}
	return obj;
}

namespace {
	float SampleHeight(const TerrainHeights& h, float gx, float gz)
	{
		const int n = h.resolution;
		gx = std::clamp(gx, 0.0f, static_cast<float>(n - 1));
		gz = std::clamp(gz, 0.0f, static_cast<float>(n - 1));
		const int x0 = (std::min)(static_cast<int>(gx), n - 2);
		const int z0 = (std::min)(static_cast<int>(gz), n - 2);
		const float tx = gx - static_cast<float>(x0);
		const float tz = gz - static_cast<float>(z0);
		const float a = h.At(x0, z0) + (h.At(x0 + 1, z0) - h.At(x0, z0)) * tx;
		const float b = h.At(x0, z0 + 1) + (h.At(x0 + 1, z0 + 1) - h.At(x0, z0 + 1)) * tx;
		return a + (b - a) * tz;
	}
}

float TerrainHeightAt(const TerrainHeights& heights, float u, float v)
{
	if (heights.resolution < 2 || heights.values.size() < static_cast<size_t>(heights.resolution) * heights.resolution) return 0.0f;
	const float cells = static_cast<float>(heights.resolution - 1);
	return SampleHeight(heights, std::isfinite(u) ? u * cells : 0.0f, std::isfinite(v) ? v * cells : 0.0f);
}

void SculptTerrain(TerrainHeights& heights, float u, float v, float radius, float strength, TerrainBrush brush, float flattenTo)
{
	const int n = heights.resolution;
	if (n < 2 || heights.values.size() < static_cast<size_t>(n) * n) return;
	if (!std::isfinite(u) || !std::isfinite(v) || !std::isfinite(radius) || !std::isfinite(strength) || !(radius > 0.0f)) return;
	const float r = radius * static_cast<float>(n - 1);
	const float cx = u * static_cast<float>(n - 1);
	const float cz = v * static_cast<float>(n - 1);
	const int minX = (std::max)(static_cast<int>(std::floor(cx - r)), 0);
	const int maxX = (std::min)(static_cast<int>(std::ceil(cx + r)), n - 1);
	const int minZ = (std::max)(static_cast<int>(std::floor(cz - r)), 0);
	const int maxZ = (std::min)(static_cast<int>(std::ceil(cz + r)), n - 1);
	const TerrainHeights before = brush == TerrainBrush::Smooth ? heights : TerrainHeights{};
	const float target = std::clamp(std::isfinite(flattenTo) ? flattenTo : 0.5f, 0.0f, 1.0f);
	for (int z = minZ; z <= maxZ; ++z) {
		for (int x = minX; x <= maxX; ++x) {
			const float d = std::sqrt((x - cx) * (x - cx) + (z - cz) * (z - cz)) / r;
			if (d >= 1.0f) continue;
			const float weight = (1.0f - d * d) * (1.0f - d * d); // soft edge
			float& value = heights.values[static_cast<size_t>(z) * n + x];
			switch (brush) {
			case TerrainBrush::Raise: value += strength * weight; break;
			case TerrainBrush::Lower: value -= strength * weight; break;
			case TerrainBrush::Flatten: value += (target - value) * std::clamp(strength * weight, 0.0f, 1.0f); break;
			case TerrainBrush::Smooth: {
				float sum = 0.0f;
				int count = 0;
				for (int dz = -1; dz <= 1; ++dz) {
					for (int dx = -1; dx <= 1; ++dx) {
						const int sx = x + dx;
						const int sz = z + dz;
						if (sx < 0 || sz < 0 || sx >= n || sz >= n) continue;
						sum += before.At(sx, sz);
						++count;
					}
				}
				value += (sum / static_cast<float>(count) - value) * std::clamp(strength * weight, 0.0f, 1.0f);
				break;
			}
			}
			value = std::clamp(value, 0.0f, 1.0f);
		}
	}
}

bool RaycastTerrain(const TerrainHeights& heights, float size, float height, const Vector3& origin, const Vector3& direction, float& u, float& v)
{
	const int n = heights.resolution;
	if (n < 2 || heights.values.size() < static_cast<size_t>(n) * n || !(size > 0.0f)) return false;
	const float length = std::sqrt(direction.x * direction.x + direction.y * direction.y + direction.z * direction.z);
	if (!(length > 1.0e-6f) || !std::isfinite(length)) return false;
	const Vector3 dir{ direction.x / length, direction.y / length, direction.z / length };
	// Clip the ray to the terrain's box
	const float half = size * 0.5f;
	const float top = (std::max)(height, 0.0f) + 0.001f;
	float tMin = 0.0f;
	float tMax = 1.0e9f;
	const float lo[3] = { -half, -0.001f, -half };
	const float hi[3] = { half, top, half };
	const float o[3] = { origin.x, origin.y, origin.z };
	const float d[3] = { dir.x, dir.y, dir.z };
	for (int axis = 0; axis < 3; ++axis) {
		if (std::abs(d[axis]) < 1.0e-8f) {
			if (o[axis] < lo[axis] || o[axis] > hi[axis]) return false;
			continue;
		}
		float t0 = (lo[axis] - o[axis]) / d[axis];
		float t1 = (hi[axis] - o[axis]) / d[axis];
		if (t0 > t1) std::swap(t0, t1);
		tMin = (std::max)(tMin, t0);
		tMax = (std::min)(tMax, t1);
		if (tMin > tMax) return false;
	}
	const float cell = size / static_cast<float>(n - 1);
	const auto above = [&](float t) {
		const float x = origin.x + dir.x * t;
		const float z = origin.z + dir.z * t;
		const float ground = SampleHeight(heights, (x + half) / cell, (z + half) / cell) * height;
		return origin.y + dir.y * t - ground;
	};
	// March half a cell at a time, then narrow down the crossing
	const float step = cell * 0.5f;
	float previous = tMin;
	if (above(previous) <= 0.0f) {
		u = std::clamp((origin.x + dir.x * previous + half) / size, 0.0f, 1.0f);
		v = std::clamp((origin.z + dir.z * previous + half) / size, 0.0f, 1.0f);
		return true;
	}
	for (float t = tMin + step;; t += step) {
		const float now = (std::min)(t, tMax);
		if (above(now) <= 0.0f) {
			float a = previous;
			float b = now;
			for (int i = 0; i < 20; ++i) {
				const float mid = (a + b) * 0.5f;
				(above(mid) > 0.0f ? a : b) = mid;
			}
			u = std::clamp((origin.x + dir.x * b + half) / size, 0.0f, 1.0f);
			v = std::clamp((origin.z + dir.z * b + half) / size, 0.0f, 1.0f);
			return true;
		}
		if (now >= tMax) return false;
		previous = now;
	}
}

std::vector<uint8_t> EncodeTerrainHeights(const TerrainHeights& heights)
{
	std::vector<uint8_t> bytes(8 + heights.values.size() * sizeof(float));
	bytes[0] = 'R'; bytes[1] = 'Z'; bytes[2] = 'T'; bytes[3] = 'H';
	const int32_t resolution = heights.resolution;
	std::memcpy(bytes.data() + 4, &resolution, 4);
	if (!heights.values.empty()) std::memcpy(bytes.data() + 8, heights.values.data(), heights.values.size() * sizeof(float));
	return bytes;
}

bool DecodeTerrainHeights(const std::vector<uint8_t>& bytes, TerrainHeights& out)
{
	if (bytes.size() < 8 || bytes[0] != 'R' || bytes[1] != 'Z' || bytes[2] != 'T' || bytes[3] != 'H') return false;
	int32_t resolution = 0;
	std::memcpy(&resolution, bytes.data() + 4, 4);
	if (resolution < kMinResolution || resolution > kMaxResolution) return false;
	const size_t count = static_cast<size_t>(resolution) * resolution;
	if (bytes.size() != 8 + count * sizeof(float)) return false;
	TerrainHeights heights;
	heights.resolution = resolution;
	heights.values.resize(count);
	std::memcpy(heights.values.data(), bytes.data() + 8, count * sizeof(float));
	for (float& value : heights.values) value = std::isfinite(value) ? std::clamp(value, 0.0f, 1.0f) : 0.0f;
	out = std::move(heights);
	return true;
}
